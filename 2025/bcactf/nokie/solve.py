import turtle

t = turtle.Turtle()
t.hideturtle()
t.speed(0)
t.pensize(2)
t.color("#ff0000")

def line(x1, y1, x2, y2):
    t.penup()
    t.goto(x1-100, 200-y1)
    t.pendown()
    t.goto(x2-100, 200-y2)

def rect(x, y, w, h):
    t.penup()
    t.goto(x-100, 200-y)
    t.pendown()
    for _ in range(2):
        t.forward(w)
        t.right(90)
        t.forward(h)
        t.right(90)

